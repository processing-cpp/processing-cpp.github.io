#!/usr/bin/env python3
"""Generate sibling Processing mode websites (Lua, Rust, Scheme) and a
shared mode-switcher nav.js for the C++ site.

Run from the root of processing-cpp.github.io:
    python3 make_mode_sites.py
Sites are written next to it: ../processing-lua.github.io, etc.
"""
from pathlib import Path

AUTHOR = "llamasjc"
GITHUB = f"https://github.com/{AUTHOR}"
DISCORD = "https://discord.gg/Un3DFmrUje"
EMAIL = "jose@llamasj.com"

MODES = {
    "cpp":    {"name": "C++",    "site": "https://processing-cpp.github.io",    "color": "#e8b400", "dark": "#b8860b", "badge": "C++"},
    "lua":    {"name": "Lua",    "site": "https://processing-lua.github.io",    "color": "#2c6bd6", "dark": "#1d4a96", "badge": "Lua"},
    "rust":   {"name": "Rust",   "site": "https://processing-rust.github.io",   "color": "#ce422b", "dark": "#93301f", "badge": "Rs"},
    "scheme": {"name": "Scheme", "site": "https://processing-scheme.github.io", "color": "#8a4fd1", "dark": "#5f3394", "badge": "λ"},
}


def nav_js(key):
    m = MODES[key]
    if key == "cpp":
        pages = [("What's New", "whats-new"), None, ("Libraries", "libraries"),
                 ("Downloads", "downloads"), ("Tutorials", "tutorials"),
                 ("Reference", "reference"), ("Examples", "examples"),
                 ("Editor", "editor"), ("About", "about")]
        logo = "'<img src=\"' + P + 'assets/cpp-logo.png\" alt=\"\" style=\"height:28px;\">'"
        extra_top = "'<a href=\"' + P + 'errors/\" style=\"margin-left:auto;color:#555;text-decoration:none;font-size:14px;\">Errors</a>'"
        search = "var s=document.createElement('script');s.src=P+'assets/search.js';document.body.appendChild(s);"
    else:
        pages = [("Downloads", "downloads"), ("Tutorials", "tutorials"), ("About", "about")]
        logo = (f"'<span style=\"display:inline-flex;align-items:center;justify-content:center;"
                f"min-width:28px;height:28px;padding:0 6px;border-radius:6px;background:{m['color']};"
                f"color:#fff;font-weight:700;font-size:13px;\">{m['badge']}</span>'")
        extra_top = "''"
        search = ""
    items = []
    for p in pages:
        if p is None:
            items.append("'<hr style=\"border:none;border-top:1px solid #eee;margin:8px 0;\">'")
        else:
            items.append(f"link('{p[0]}', '{p[1]}/')")
    modes = []
    for k, mm in MODES.items():
        cur = " current" if k == key else ""
        modes.append(f"'<a class=\"mode-link{cur}\" style=\"--mc:{mm['color']}\" href=\"{mm['site']}/\">{mm['name']}</a>'")
    return f"""// Shared navigation for Processing {m['name']} Mode. Generated by make_mode_sites.py.
(function () {{
  var parts = location.pathname.replace(/\\/index\\.html$/, '/').split('/').filter(Boolean);
  var depth = location.pathname.endsWith('/') ? parts.length : Math.max(parts.length - 1, 0);
  var P = depth ? '../'.repeat(depth) : './';
  var here = parts[0] || '';
  function link(label, path) {{
    var on = here && path.indexOf(here + '/') === 0;
    return '<a href="' + P + path + '" class="side-link' + (on ? ' active' : '') + '">' + label + '</a>';
  }}
  var css = document.createElement('style');
  css.textContent =
    '#site-nav{{display:flex;align-items:center;gap:10px;padding:10px 20px;border-bottom:1px solid #eee;background:#fff;font-family:"Space Grotesk",sans-serif;}}' +
    '#site-nav .brand{{display:flex;align-items:center;gap:8px;text-decoration:none;color:#003f6b;font-weight:600;}}' +
    '.side-link{{display:block;padding:6px 12px;color:#555;text-decoration:none;border-radius:4px;font-size:14px;}}' +
    '.side-link:hover,.side-link.active{{background:#f3f3f3;color:#111;}}' +
    '.side-title{{font-size:11px;text-transform:uppercase;letter-spacing:.08em;color:#999;padding:14px 12px 4px;}}' +
    '.mode-link{{display:block;padding:5px 10px;margin:2px 0;border-left:3px solid var(--mc);color:#555;text-decoration:none;font-size:14px;}}' +
    '.mode-link.current{{background:#f7f7f7;color:#111;font-weight:600;}}' +
    '#nav-toggle{{display:none;background:none;border:1px solid #ddd;border-radius:4px;padding:4px 8px;cursor:pointer;}}' +
    '@media(max-width:800px){{#nav-toggle{{display:inline-block;}}}}';
  document.head.appendChild(css);
  var nav = document.getElementById('site-nav');
  if (nav) nav.innerHTML =
    '<button id="nav-toggle" aria-label="Menu">&#9776;</button>' +
    '<a class="brand" href="' + P + '">' + {logo} + '<span>Processing <span style="color:{m['color']}">{m['name']}</span></span></a>' +
    {extra_top};
  var side = document.getElementById('site-sidebar') || document.getElementById('sidebar');
  if (side) side.innerHTML =
    {' + '.join(items)} +
    '<a class="side-link" href="{DISCORD}" target="_blank" rel="noopener" style="color:#5865F2;">Discord</a>' +
    '<div class="side-title">Modes</div>' +
    {' + '.join(modes)};
  var t = document.getElementById('nav-toggle');
  if (t && side) t.onclick = function () {{
    var outer = side.closest('.sidebar-outer') || side;
    outer.classList.toggle('open');
  }};
  {search}
}})();
"""


